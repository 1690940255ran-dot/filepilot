//! 契约生成器：把 Rust 类型导出为 TypeScript 类型与 JSON Schema。
//!
//! 规格 5.1：**Rust 类型是唯一真源**，序列化统一 camelCase。
//! 规格 0.6：不得出现两套同义但不兼容的数据结构。
//!
//! 运行：`cargo run --manifest-path src-tauri/Cargo.toml --bin export-contracts`
//! 校验：`pnpm contracts:check`（重新生成后比对，不一致即失败）

use std::fs;
use std::path::PathBuf;

use ts_rs::TS;

use filepilot_lib::ai::disclosure::{DisclosureGrant, DisclosurePreview};
use filepilot_lib::ai::provider::{ProviderKind, ProviderProbe, ProviderSummary};
use filepilot_lib::commands_recovery::{BlockedRun, RecoveryStatus};
use filepilot_lib::domain::errors::AppError;
use filepilot_lib::domain::types::{
    AppSettings, Evidence, Extraction, ExtractionStatus, FilePage, FileRecord, Fingerprint, Issue,
    Mode, OpResolution, OpStatus, Plan, PlanAction, PlanItem, PlanItemEdit, PlanItemOrigin,
    PlanStatus, Proposal, RecoveryItem, RecoveryReport, Risk, RootSummary, RunCounts, RunItem,
    RunItems, RunReport, RunStatus, ScanSummary, TaskError, TaskStatus, TaskSummary, UndoItem,
    UndoOutcome, UndoPreview, UndoReport, UndoStatus, ValidationReport,
};
use filepilot_lib::extractors::protocol::OcrAvailabilityReport;
use filepilot_lib::planner::PlanBuild;
use filepilot_lib::rules::RuleKind;

const SCHEMA_ID: &str = "https://filepilot.local/contracts.schema.json";

const TS_HEADER: &str = "\
// This file was generated by [ts-rs](https://github.com/Aleph-Alpha/ts-rs). Do not edit this file manually.
//
// 生成命令：pnpm contracts:generate
// 真源：src-tauri/src/domain/types.rs 与 src-tauri/src/domain/errors.rs
// 手工修改本文件会导致 `pnpm contracts:check` 失败。

/** 应用内标识。UUID 字符串。不等同于 Windows 文件身份，也不等同于内容哈希。 */
export type Id = string

/** 相对路径以组件数组表示，例如 [\"学习\", \"数学\", \"第三章.pdf\"]。 */
export type RelPath = Array<string>

";

const TS_RESULT_ALIAS: &str = "
/**
 * IPC 返回信封，对应 Rust 的 `IpcResult<T>`（src-tauri/src/domain/ipc.rs）。
 *
 * 它没有从 Rust 侧生成，原因是契约要求的是布尔量 `ok` 字段，
 * 而 serde 的 tag 机制只能生成变体名字符串。信封本身有单元测试保证形状。
 */
export type Result<T> = { ok: true; data: T } | { ok: false; error: AppError }
";

fn main() {
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let repo_root = manifest_dir
        .parent()
        .expect("src-tauri 必须位于仓库根目录下")
        .to_path_buf();

    let ts_path = repo_root
        .join("src")
        .join("api")
        .join("contracts.generated.ts");
    let schema_path = repo_root
        .join("src")
        .join("api")
        .join("contracts.schema.json");

    if let Some(parent) = ts_path.parent() {
        fs::create_dir_all(parent).expect("创建 src/api 目录失败");
    }

    let ts_content = generate_typescript();
    fs::write(&ts_path, ts_content).expect("写入 contracts.generated.ts 失败");

    let schema_content = generate_json_schema();
    let schema_pretty =
        serde_json::to_string_pretty(&schema_content).expect("序列化 JSON Schema 失败");
    fs::write(&schema_path, format!("{schema_pretty}\n")).expect("写入 contracts.schema.json 失败");

    println!("contracts written:");
    println!("  {}", ts_path.display());
    println!("  {}", schema_path.display());
}

/// 生成 TypeScript 契约文件。
fn generate_typescript() -> String {
    let mut out = String::from(TS_HEADER);

    // ts-rs 12 的 `TS::decl()` 需要一个 `&Config`（旧版本是无参的）。
    // 这里只用它的声明生成能力，不落盘到 export_dir，因此默认 Config 即可。
    let config = ts_rs::Config::new();

    // 枚举与结构体按类型系统顺序排列，保证输出稳定（相同输入得到相同文件）
    emit(&mut out, Mode::decl(&config));
    emit(&mut out, Risk::decl(&config));
    emit(&mut out, ExtractionStatus::decl(&config));
    emit(&mut out, TaskStatus::decl(&config));
    emit(&mut out, RunStatus::decl(&config));
    emit(&mut out, OpStatus::decl(&config));
    emit(&mut out, OpResolution::decl(&config));
    emit(&mut out, UndoStatus::decl(&config));
    emit(&mut out, PlanStatus::decl(&config));
    emit(&mut out, PlanAction::decl(&config));
    emit(&mut out, PlanItemOrigin::decl(&config));

    emit(&mut out, Fingerprint::decl(&config));
    emit(&mut out, FileRecord::decl(&config));
    emit(&mut out, Evidence::decl(&config));
    emit(&mut out, Extraction::decl(&config));
    emit(&mut out, Proposal::decl(&config));
    emit(&mut out, PlanItem::decl(&config));
    emit(&mut out, Plan::decl(&config));
    emit(&mut out, Issue::decl(&config));
    emit(&mut out, ValidationReport::decl(&config));
    emit(&mut out, RunCounts::decl(&config));
    emit(&mut out, RunReport::decl(&config));
    // PR-003：get_run_items 的返回值。`RunItem` 也必须 emit ——
    // `RunItems` 的 TS 定义会引用它（`items: Array<RunItem>`），
    // 不生成它会报「Cannot find name」。这个坑在 DisclosurePreview 上踩过两次。
    emit(&mut out, RunItem::decl(&config));
    emit(&mut out, RunItems::decl(&config));
    // T08：崩溃恢复的核对结果
    emit(&mut out, RecoveryItem::decl(&config));
    emit(&mut out, RecoveryReport::decl(&config));
    emit(&mut out, BlockedRun::decl(&config));
    emit(&mut out, RecoveryStatus::decl(&config));
    // T09：撤销与冲突（规格 8.4）
    emit(&mut out, UndoOutcome::decl(&config));
    emit(&mut out, UndoItem::decl(&config));
    emit(&mut out, UndoPreview::decl(&config));
    emit(&mut out, UndoReport::decl(&config));
    emit(&mut out, AppError::decl(&config));
    emit(&mut out, AppSettings::decl(&config));
    // T11：图片 OCR 状态（设置页显示可用性）
    emit(&mut out, OcrAvailabilityReport::decl(&config));
    // T12：提供商配置（设置页显示与保存；**不含密钥**）
    emit(&mut out, ProviderKind::decl(&config));
    emit(&mut out, ProviderSummary::decl(&config));
    emit(&mut out, ProviderProbe::decl(&config));
    // T13：待发送载荷的预览与授权（**不含正文全文**，只有开头若干字符）
    emit(&mut out, DisclosurePreview::decl(&config));
    // 嵌套类型也必须 emit：`DisclosurePreview` 的 TS 定义会**引用**它
    // （`items: Array<DisclosureItemPreview>`），不生成它会让 tsc 报
    // 「Cannot find name」——这个错真实发生过，是 `tsc --noEmit` 抓住的。
    emit(
        &mut out,
        filepilot_lib::ai::disclosure::DisclosureItemPreview::decl(&config),
    );
    // 同上：`DisclosureItemPreview` 引用它。被引用的类型必须 emit，
    // 否则 tsc 报「Cannot find name」——这个坑踩过两次了。
    emit(
        &mut out,
        filepilot_lib::ai::disclosure::DisclosureTextStatus::decl(&config),
    );
    emit(&mut out, DisclosureGrant::decl(&config));
    // T13：开始分析的返回（taskId + analysisId）
    emit(
        &mut out,
        filepilot_lib::commands_analysis::AnalysisStart::decl(&config),
    );

    // T02：根授权、扫描任务与分页
    emit(&mut out, RootSummary::decl(&config));
    emit(&mut out, ScanSummary::decl(&config));
    emit(&mut out, FilePage::decl(&config));
    emit(&mut out, TaskError::decl(&config));
    emit(&mut out, TaskSummary::decl(&config));

    // T05：计划编辑与一次性确认
    emit(&mut out, RuleKind::decl(&config));
    emit(&mut out, PlanItemEdit::decl(&config));
    emit(&mut out, PlanBuild::decl(&config));

    out.push_str(TS_RESULT_ALIAS);
    out
}

/// ts-rs 的 `decl()` 产出的是**裸**声明（不含 `export`），因为它默认服务于
/// 「每个类型一个文件、由 `export_to` 负责落盘」的场景。我们把所有类型汇总到
/// 同一个文件，必须自己补上 `export`，否则前端一个类型都 import 不到。
fn emit(out: &mut String, declaration: String) {
    let declaration = declaration.trim_end();
    for keyword in ["type ", "interface ", "enum ", "const "] {
        if let Some(rest) = declaration.strip_prefix(keyword) {
            out.push_str("export ");
            out.push_str(keyword);
            out.push_str(rest);
            out.push_str("\n\n");
            return;
        }
    }
    // 认不出的形状原样输出，宁可让人看见异常，也不要静默丢掉内容
    out.push_str(declaration);
    out.push_str("\n\n");
}

/// 生成 JSON Schema，供前端 Ajv 做运行时校验（ADR-006）。
///
/// 覆盖前端当前真正会收到并校验的类型。其余类型随对应阶段的 IPC 命令一起加入，
/// 避免生成大量当前无人消费的定义。
fn generate_json_schema() -> serde_json::Value {
    let mut definitions = serde_json::Map::new();

    definitions.insert("AppSettings".to_owned(), schema_value::<AppSettings>());
    definitions.insert(
        "OcrAvailabilityReport".to_owned(),
        schema_value::<OcrAvailabilityReport>(),
    );
    // T12：设置页要读的是 ProviderSummary（不含密钥），
    // 而它引用的 ProviderKind 也必须进 schema，否则 Ajv 编译不过。
    definitions.insert("ProviderKind".to_owned(), schema_value::<ProviderKind>());
    definitions.insert(
        "ProviderSummary".to_owned(),
        schema_value::<ProviderSummary>(),
    );
    definitions.insert("ProviderProbe".to_owned(), schema_value::<ProviderProbe>());
    // T13：两者都引用嵌套类型（`DisclosureItemPreview`），也必须进 schema，
    // 否则 Ajv 编译不过。
    definitions.insert(
        "DisclosurePreview".to_owned(),
        schema_value::<DisclosurePreview>(),
    );
    definitions.insert(
        "DisclosureGrant".to_owned(),
        schema_value::<DisclosureGrant>(),
    );
    definitions.insert(
        "DisclosureItemPreview".to_owned(),
        schema_value::<filepilot_lib::ai::disclosure::DisclosureItemPreview>(),
    );
    definitions.insert(
        "DisclosureTextStatus".to_owned(),
        schema_value::<filepilot_lib::ai::disclosure::DisclosureTextStatus>(),
    );
    definitions.insert(
        "AnalysisStart".to_owned(),
        schema_value::<filepilot_lib::commands_analysis::AnalysisStart>(),
    );
    definitions.insert("AppError".to_owned(), schema_value::<AppError>());
    definitions.insert("RootSummary".to_owned(), schema_value::<RootSummary>());
    definitions.insert("ScanSummary".to_owned(), schema_value::<ScanSummary>());
    definitions.insert("FilePage".to_owned(), schema_value::<FilePage>());
    definitions.insert("TaskError".to_owned(), schema_value::<TaskError>());
    definitions.insert("TaskSummary".to_owned(), schema_value::<TaskSummary>());
    definitions.insert("RuleKind".to_owned(), schema_value::<RuleKind>());
    definitions.insert("PlanItemEdit".to_owned(), schema_value::<PlanItemEdit>());
    definitions.insert("PlanBuild".to_owned(), schema_value::<PlanBuild>());
    // get_plan / validate_plan 的返回值也要能被前端运行时校验
    definitions.insert("Plan".to_owned(), schema_value::<Plan>());
    definitions.insert(
        "ValidationReport".to_owned(),
        schema_value::<ValidationReport>(),
    );
    // execute_plan / get_run 的返回值
    definitions.insert("RunReport".to_owned(), schema_value::<RunReport>());
    // PR-003：get_run_items 的返回值，以及它引用的 RunItem。
    //
    // 两者都必须进 schema：`RunItems` 内联了 `RunItem`，少登记 `RunItem`
    // 前端 `decodeResponse` 会在运行时找不到定义直接抛错——
    // 那种失败看起来像「历史打不开了」，实际是契约漏登记。
    definitions.insert("RunItem".to_owned(), schema_value::<RunItem>());
    definitions.insert("RunItems".to_owned(), schema_value::<RunItems>());
    // T08：get_recovery / acknowledge_recovery / recover_pending_runs 的返回值
    definitions.insert("RecoveryItem".to_owned(), schema_value::<RecoveryItem>());
    definitions.insert(
        "RecoveryReport".to_owned(),
        schema_value::<RecoveryReport>(),
    );
    definitions.insert(
        "RecoveryStatus".to_owned(),
        schema_value::<RecoveryStatus>(),
    );
    // T09：preview_undo / execute_undo / get_undo_report 的返回值。
    //
    // 这几个**必须**进 schema，否则前端 `decodeResponse` 找不到定义会直接抛错——
    // 而那种失败发生在运行时，看起来像「撤销功能坏了」，实际是契约漏登记。
    definitions.insert("UndoOutcome".to_owned(), schema_value::<UndoOutcome>());
    definitions.insert("UndoItem".to_owned(), schema_value::<UndoItem>());
    definitions.insert("UndoPreview".to_owned(), schema_value::<UndoPreview>());
    definitions.insert("UndoReport".to_owned(), schema_value::<UndoReport>());

    let mut root = serde_json::Map::new();
    root.insert(
        "$schema".to_owned(),
        serde_json::Value::String("http://json-schema.org/draft-07/schema#".to_owned()),
    );
    root.insert(
        "$id".to_owned(),
        serde_json::Value::String(SCHEMA_ID.to_owned()),
    );
    root.insert(
        "title".to_owned(),
        serde_json::Value::String("FilePilot IPC Contracts".to_owned()),
    );
    root.insert(
        "description".to_owned(),
        serde_json::Value::String(
            "由 src-tauri/src/bin/export-contracts.rs 生成，真源为 Rust 类型。\
             运行时校验使用 additionalProperties=false，拒绝未知字段（规格 6.4）。"
                .to_owned(),
        ),
    );
    root.insert(
        "definitions".to_owned(),
        serde_json::Value::Object(definitions),
    );

    serde_json::Value::Object(root)
}

/// 取某个契约类型自身的 schema，且**完全内联**。
///
/// 两个关键设置：
///
/// 1. **`for_serialize()`** —— schemars 默认按「反序列化契约」生成，会把 `Option<T>`
///    视为「字段可缺失」，于是 `sha256: Option<String>` 这类字段被排除在 `required` 之外。
///    但我们的契约是**后端发给前端**的，Rust 序列化 `Option::None` 会输出 `null`，
///    字段**必然存在**，契约上是 `sha256: string | null` 这种必填可空。
///    切到序列化契约后，`Option<T>` 会自动进入 `required` 且保留 `null`。
///    （注：不要改用 `#[schemars(required)]`——它会把 `Option<T>` 当 `T` 处理，
///    连 `null` 一起吃掉，见 schemars `_private/mod.rs` 的 nullable 包装逻辑。）
///
/// 2. **`inline_subschemas`** —— 如果生成的 schema 里出现 `$ref`，Ajv 就必须先知道
///    被引用定义的位置，而 schemars 默认把定义放在 `$defs` 下、契约文件用的是
///    `definitions`。让 `$ref` 彻底不出现，可以消掉这条容易出错的隐式依赖。
fn schema_value<T: schemars::JsonSchema>() -> serde_json::Value {
    use schemars::generate::SchemaSettings;

    let generator = SchemaSettings::draft07()
        .with(|settings| {
            settings.inline_subschemas = true;
            settings.meta_schema = None;
        })
        .for_serialize()
        .into_generator();

    let mut value = to_json(generator.into_root_schema_for::<T>());
    strip_wrapper_keys(&mut value);
    value
}

/// 去掉类型名外面那层元数据包装。
///
/// 键名 `title` 在 `definitions` 里是冗余的（键本身就是类型名）；
/// `$defs` / `definitions` / `$schema` / `$id` 属于文件级元数据，
/// 留在每个定义内部会让 Ajv 在 `strict` 模式下产生歧义。
fn strip_wrapper_keys(value: &mut serde_json::Value) {
    const WRAPPER_KEYS: [&str; 6] = [
        "$schema",
        "$id",
        "title",
        "$defs",
        "definitions",
        "$comment",
    ];

    match value {
        serde_json::Value::Object(map) => {
            for key in WRAPPER_KEYS {
                map.remove(key);
            }
            for nested in map.values_mut() {
                strip_wrapper_keys(nested);
            }
        }
        serde_json::Value::Array(items) => {
            for item in items.iter_mut() {
                strip_wrapper_keys(item);
            }
        }
        _ => {}
    }
}

fn to_json<T: serde::Serialize>(value: T) -> serde_json::Value {
    serde_json::to_value(value).expect("序列化 schema 失败")
}
