//! 规格 6.2 的内容提取限制。
//!
//! 这些数字全部来自规格表格，**集中放在一处**而不是散在各个解析器里。
//! 理由很直接：规格的这条表格是一张「承诺给用户的上限表」，
//! 分散之后必然出现「TXT 说 10 MiB、DOCX 忘了检查」这种不一致，
//! 而用户看到的是「我按说明放了个 15 MiB 的 PDF，它卡住了」。
//!
//! 单位统一用字节；字符数上限按 **Unicode 标量**计（`chars().count()`），
//! 不是字节——规格写的是「12,000 个 Unicode 字符」。

/// 每个文件一次提取最多产出多少字符（规格 6.2 的 12,000）。
///
/// 超出即截断并置 `truncated`，不是失败：用户要的是「够拿去分类」，
/// 而不是「把整本书读完」。截断必须如实上报，否则界面上会把
/// 「只看了结论的第一段」当成「读完了」。
pub const MAX_EXTRACTED_CHARS: usize = 12_000;

/// 文本类文件（TXT/MD）的大小上限。
pub const MAX_TEXT_BYTES: u64 = 10 * 1024 * 1024;

/// PDF 文件的大小上限。
pub const MAX_PDF_BYTES: u64 = 20 * 1024 * 1024;

/// 从 PDF 中最多读前多少页。
///
/// 不是「随便取个整数」：扫描型 PDF 每页都是一张图，页数直接决定
/// 解析耗时与内存；而分类这件事在前几页就已经能看出主题。
pub const MAX_PDF_PAGES: u32 = 10;

/// 加载 PDF 时**单个流**解压后的上限。
///
/// PDF 的对象流与交叉引用流在加载阶段就会被解压，而一个几百字节的
/// 压缩流可以膨胀成几个 GiB。它是「文件 ≤20 MiB」这条限制**管不到**的一面：
/// 限制的是输入大小，膨胀发生在解压之后。
pub const MAX_PDF_STREAM_BYTES: usize = 16 * 1024 * 1024;

/// PNG / JPEG 的文件大小上限（规格 6.2 第四行）。
pub const MAX_IMAGE_BYTES: u64 = 10 * 1024 * 1024;

/// 图片**解码后**的像素总数上限（规格 6.2：≤2000 万）。
///
/// 注意这条与「文件 ≤ 10 MiB」是两回事：一个 2 MiB 的 PNG 可以解出
/// 4 亿像素，按文件大小根本挡不住。而且它只能在**读出图片头**之后判定，
/// 所以顺序是「读头 → 判像素 → 再解码」，不是「解码完再看大不大」。
pub const MAX_IMAGE_PIXELS: u64 = 20_000_000;

/// 单个 PDF 页面**内容流**解压后的上限。
///
/// 页面内容是一串绘制指令，正常一页几十到几百 KiB。
/// 超过 8 MiB 说明这一页在构造上就不正常（或者是个炸弹），
/// 与其把它读进内存再交给文本提取，不如在这里停下。
pub const MAX_PDF_PAGE_CONTENT_BYTES: usize = 8 * 1024 * 1024;

/// DOCX 压缩包本身的大小上限。
pub const MAX_DOCX_BYTES: u64 = 20 * 1024 * 1024;

/// DOCX 解压后**所有条目累计**的上限。
///
/// 这一条是防压缩炸弹的主闸：压缩包只有 20 MiB，解压出来可能是 20 GiB。
pub const MAX_DOCX_UNCOMPRESSED_BYTES: u64 = 50 * 1024 * 1024;

/// 单个条目的压缩比上限。
///
/// 1 MiB 压成 10 KiB 是正常的（重复文本），1 MiB 压成 1 KiB 就不是了。
/// 取 100 是规格给的值。
pub const MAX_DOCX_COMPRESSION_RATIO: u64 = 100;

/// 单个文件提取的超时（毫秒）。
pub const EXTRACT_TIMEOUT_MS: u64 = 15_000;

/// 同时最多几个提取在跑。
///
/// 每个提取都是一个独立进程，各自可能吃满 256 MiB；
/// 并发上限直接决定内存峰值，因此它是资源策略而不是性能调优。
pub const EXTRACT_CONCURRENCY: usize = 2;

/// 工作进程的工作集上限（字节）。
pub const WORKER_MEMORY_LIMIT_BYTES: u64 = 256 * 1024 * 1024;

/// 提取产出的证据片段最多保留多少条。
///
/// 规格 6.4 要求 `evidenceLocator` 必须对应**真实提取结果**，
/// 前端据此展示片段。留太多条没有意义，只会让响应变大。
pub const MAX_EVIDENCE: usize = 8;

/// 一条证据片段最多多少字符。
pub const MAX_EVIDENCE_CHARS: usize = 160;

/// 判「这段字节是乱码」的可疑字符占比阈值（千分比）。
///
/// 规格 6.2 要求「乱码明确失败」。**只数 U+FFFD 是不够的**：
/// GB18030 几乎能把任意字节序列映射成**某些**字符——未定义的位置
/// 会被映射进私用区（PUA），而不是替换字符。实测一段 0x00..0xFF 循环的
/// 随机字节按 GB18030 解出来几乎没有 U+FFFD，却满是 PUA 与控制字符。
///
/// 因此判据是三类的合计占比：
/// * U+FFFD —— 明确说不出原文的位置；
/// * C0/C1 控制字符（`\t`/`\n`/`\r` 除外）—— 正文里不该成片出现；
/// * 私用区 U+E000–U+F8FF —— GB18030 兜底映射的落点。
///
/// 取 50‰ 而不是「出现即失败」：正常文档里也可能有几个不可映射字符，
/// 出现即失败会误伤。
pub const GARBLED_MARK_PERMILLE: usize = 50;
